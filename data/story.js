/* 전선 1장의 **대사 스크립트** — `docs/story/chapter1.txt` 에서 뽑았다.
 *
 * 왜 따로 있나 — `data/front.js` 는 칸의 **배치**(레벨·적·보상)이고 여기는 **말**이다.
 * 둘을 섞으면 수치를 고치러 온 사람이 대사 사이를 헤매고, 대사를 고치러 온 사람이
 * 밸런스 표를 밟는다. 담당도 다르다(배치는 밸런스, 말은 아니다).
 *
 * ── 한 칸이 이렇게 흐른다 ─────────────────────────────
 *   before  →  전투  →  after(이겼을 때만)
 * 지면 after 를 안 본다. 이야기가 앞으로 안 갔으니 당연하고, **다시 왔을 때
 * 같은 대사를 처음부터 다시 보지 않게** before 도 한 번 본 칸은 건너뛴다(화면이 정한다).
 *
 * ── 말투 ──────────────────────────────────────────────
 * 원작이 짧은 문장으로 끊어 간다. 그 호흡을 지킨다 — 한 beat 는 **한 호흡**이다.
 * 길게 쓰면 캠페인이 아니라 소설 요약이 된다(그게 지금까지의 문제였다).
 *
 * beat 모양: { s:'화자키', t:'대사', art:'삽화키' }
 *   s 를 비우면 나레이션이다. SPEAKERS 에 없는 키는 화면이 이름 그대로 쓴다.
 *
 * ── art — 삽화 자리 ───────────────────────────────────
 * **한 줄에 한 장이 아니라 한 장면에 한 장이다.** art 를 적은 beat 에서 그림이 바뀌고,
 * 안 적은 beat 는 앞 그림을 그대로 쓴다(시각소설의 배경과 같은 규칙).
 * `art: null` 이면 그림을 걷어내고 지형 배경이 비친다.
 *
 * 파일은 `assets/story/<키>.webp` 다(`ART_DIR`·`ART_EXT`).
 * **아직 한 장도 없다.** 없으면 화면이 그림 칸을 통째로 접는다 — 깨진 이미지가 안 뜬다.
 * 그림이 생기면 파일만 넣으면 되고 코드는 안 바뀐다. `assets/story/README.md` 참고.
 */
