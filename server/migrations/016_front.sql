-- 전선(F장 1단계) — 칸별 진행과 도감을 담을 칸 둘.
--
-- **별도 표를 쓰지 않는다.** D1 과금이 '읽은 행' 기준이라, 표를 따로 두면 전선 화면을
-- 열 때마다 칸 수만큼 행을 읽는다. `player` 는 어차피 모든 요청이 한 행을 읽으므로
-- 여기에 컬럼을 더하면 **읽기가 하나도 안 는다**(기존 쿼리는 전부 컬럼 지정형이라
-- SELECT 목록에 이름만 더하면 된다).
--
-- 두 칸을 한 번에 만드는 이유 — 도감은 아직 안 짓는다(F장 §7). 그래도 같이 만든다.
-- 마이그레이션을 두 번 돌리는 값이 컬럼 하나가 노는 값보다 비싸다.

-- 칸별 진행. 한 칸에 한 글자다.
--   '0' 아직 · '1' 깬 것
-- 1장이 5칸이므로 '00000'. 장이 늘면 뒤에 붙는다 — 길이로 장 수를 알 수 있다.
-- 숫자 하나로 비트를 쓰지 않는 이유: 사람이 DB 를 눈으로 볼 때 바로 읽히고,
-- 나중에 별(0~3)을 넣게 되면 같은 자리에 '2'·'3' 을 쓰면 되어 모양이 안 바뀐다.
ALTER TABLE player ADD COLUMN campaign TEXT;

-- 도감. 만난 것을 표시한다. 아직 아무도 안 읽는다(F장 §7 에서 뒤로 밀었다).
ALTER TABLE player ADD COLUMN codex TEXT;

-- 기존 계정은 NULL 로 남긴다. **여기서 채우지 않는다.**
--   · NULL = '전선을 아직 한 번도 안 봤다' 이고, 코드가 그것을 빈 진행으로 읽는다
--   · 해금은 진행도 **또는** 보유 기체 레벨로 열리므로(F장 §2) 기존 32계정은
--     전선을 한 칸도 안 깨도 전부 열린 채로 보인다
--   · 전투를 한 번이라도 한 계정은 첫 화면도 지금처럼 격납고다(F장 §3 · wins+losses 로 가른다)
-- 즉 이 마이그레이션은 **기존 플레이어에게 아무것도 바꾸지 않는다.**

UPDATE meta SET v = '16' WHERE k = 'schema_version';
