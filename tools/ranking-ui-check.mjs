import assert from 'node:assert/strict';
import {rankingView,rankShell} from '../js/ui/ranking.js';

const rows=Array.from({length:23},(_,i)=>({rank:i+1,nickname:`지휘관${i+1}`,wins:23-i,losses:i,me:i===11,title:null}));
rows[0].nickname='<script>alert(1)</script>';
rows[4].title='earned';
const ranked={top:rows,total:52,ranked_at:'2026-09-27T00:00:00Z',me:{...rows[11],live:true}};
const first=rankingView(ranked,{page:0,pageSize:10,titleName:id=>id==='earned'?'<현장 지휘관>':null});
assert.match(first,/rv-place-1/);
assert.match(first,/rv-place-2/);
assert.match(first,/rv-place-3/);
assert.match(first,/&lt;script&gt;alert\(1\)&lt;\/script&gt;/);
assert.doesNotMatch(first,/<script>/);
assert.match(first,/&lt;현장 지휘관&gt;/);
assert.match(first,/12위/);
assert.match(first,/내 순위는 현재 레이팅으로 계산했습니다/);
assert.match(first,/>4<\/td>/);
assert.doesNotMatch(first,/>14<\/td>/);
assert.doesNotMatch(first,/클랜|시즌|전투력|레이팅 점수/);
const second=rankingView(ranked,{page:1,pageSize:10});
assert.match(second,/>14<\/td>/);
assert.match(second,/>23<\/td>/);
assert.doesNotMatch(second,/>4<\/td>/);
assert.match(rankShell('codex','기록','7'),/aria-current="page"[^>]*>.*도감/s);
const empty=rankingView({top:[],total:0,me:{nickname:'새 지휘관',wins:0,losses:0}},{});
assert.match(empty,/아직 순위에 오른 지휘관이 없습니다/);
assert.match(empty,/집계 중/);
assert.match(rankingView({top:rows.slice(0,1),total:1,me:rows[0]}),/rv-podium-grid rv-count-1/);
console.log('Ranking UI passed: top-three/order, actual records, paging, self outside top, escaping, empty state.');
